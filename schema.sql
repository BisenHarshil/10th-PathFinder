CREATE TABLE IF NOT EXISTS users (
    id INTEGER GENERATED BY DEFAULT AS IDENTITY PRIMARY KEY,
    name VARCHAR(100) NOT NULL,
    email VARCHAR(150) NOT NULL UNIQUE,
    password_hash VARCHAR(255) NOT NULL,
    class_level VARCHAR(20) DEFAULT '10',
    role VARCHAR(20) NOT NULL DEFAULT 'student' CHECK (role IN ('student','admin')),
    created_at TIMESTAMPTZ DEFAULT CURRENT_TIMESTAMP
);

CREATE TABLE IF NOT EXISTS streams (
    id INTEGER GENERATED BY DEFAULT AS IDENTITY PRIMARY KEY,
    name VARCHAR(80) NOT NULL UNIQUE,
    description TEXT
);

CREATE TABLE IF NOT EXISTS careers (
    id INTEGER GENERATED BY DEFAULT AS IDENTITY PRIMARY KEY,
    stream_id INTEGER REFERENCES streams(id) ON DELETE SET NULL,
    name VARCHAR(120) NOT NULL,
    slug VARCHAR(140) NOT NULL UNIQUE,
    short_description VARCHAR(500),
    subjects TEXT, skills TEXT,
    icon VARCHAR(10) DEFAULT '◎',
    featured SMALLINT DEFAULT 0
);

CREATE TABLE IF NOT EXISTS exams (
    id INTEGER GENERATED BY DEFAULT AS IDENTITY PRIMARY KEY,
    name VARCHAR(120) NOT NULL, full_name VARCHAR(255), exam_date DATE,
    description TEXT, website VARCHAR(255)
);

CREATE TABLE IF NOT EXISTS career_exams (
    career_id INTEGER NOT NULL REFERENCES careers(id) ON DELETE CASCADE,
    exam_id INTEGER NOT NULL REFERENCES exams(id) ON DELETE CASCADE,
    PRIMARY KEY(career_id, exam_id)
);

CREATE TABLE IF NOT EXISTS colleges (
    id INTEGER GENERATED BY DEFAULT AS IDENTITY PRIMARY KEY,
    career_id INTEGER NOT NULL REFERENCES careers(id) ON DELETE CASCADE,
    name VARCHAR(180) NOT NULL, location VARCHAR(120)
);

CREATE TABLE IF NOT EXISTS quiz_questions (
    id INTEGER GENERATED BY DEFAULT AS IDENTITY PRIMARY KEY,
    question_text TEXT NOT NULL, active SMALLINT DEFAULT 1
);

CREATE TABLE IF NOT EXISTS quiz_options (
    id INTEGER GENERATED BY DEFAULT AS IDENTITY PRIMARY KEY,
    question_id INTEGER NOT NULL REFERENCES quiz_questions(id) ON DELETE CASCADE,
    option_text VARCHAR(500) NOT NULL
);

CREATE TABLE IF NOT EXISTS option_career_weights (
    option_id INTEGER NOT NULL REFERENCES quiz_options(id) ON DELETE CASCADE,
    career_id INTEGER NOT NULL REFERENCES careers(id) ON DELETE CASCADE,
    weight NUMERIC(6,2) NOT NULL DEFAULT 1,
    PRIMARY KEY(option_id, career_id)
);

CREATE TABLE IF NOT EXISTS quiz_attempts (
    id INTEGER GENERATED BY DEFAULT AS IDENTITY PRIMARY KEY,
    user_id INTEGER NOT NULL REFERENCES users(id) ON DELETE CASCADE,
    created_at TIMESTAMPTZ DEFAULT CURRENT_TIMESTAMP
);

CREATE TABLE IF NOT EXISTS quiz_answers (
    id INTEGER GENERATED BY DEFAULT AS IDENTITY PRIMARY KEY,
    attempt_id INTEGER NOT NULL REFERENCES quiz_attempts(id) ON DELETE CASCADE,
    question_id INTEGER NOT NULL REFERENCES quiz_questions(id) ON DELETE CASCADE,
    option_id INTEGER NOT NULL REFERENCES quiz_options(id) ON DELETE CASCADE
);

CREATE TABLE IF NOT EXISTS attempt_results (
    id INTEGER GENERATED BY DEFAULT AS IDENTITY PRIMARY KEY,
    attempt_id INTEGER NOT NULL REFERENCES quiz_attempts(id) ON DELETE CASCADE,
    career_id INTEGER NOT NULL REFERENCES careers(id) ON DELETE CASCADE,
    score NUMERIC(8,2) NOT NULL, match_percent NUMERIC(5,2) NOT NULL
);

CREATE TABLE IF NOT EXISTS competitions (
    id INTEGER GENERATED BY DEFAULT AS IDENTITY PRIMARY KEY,
    name VARCHAR(180) NOT NULL, type VARCHAR(80) DEFAULT 'Olympiad',
    class_level VARCHAR(40) DEFAULT 'All', interest VARCHAR(80) DEFAULT 'All',
    deadline DATE, description TEXT, website VARCHAR(255)
);

CREATE TABLE IF NOT EXISTS bookmarks (
    id INTEGER GENERATED BY DEFAULT AS IDENTITY PRIMARY KEY,
    user_id INTEGER NOT NULL REFERENCES users(id) ON DELETE CASCADE,
    career_id INTEGER REFERENCES careers(id) ON DELETE CASCADE,
    competition_id INTEGER REFERENCES competitions(id) ON DELETE CASCADE,
    created_at TIMESTAMPTZ DEFAULT CURRENT_TIMESTAMP,
    CONSTRAINT unique_career_bookmark UNIQUE(user_id, career_id),
    CONSTRAINT unique_comp_bookmark UNIQUE(user_id, competition_id)
);
